#ifndef WARPX_GLOBAL_A_RECOVERY_H_
#define WARPX_GLOBAL_A_RECOVERY_H_

#include "HybridPICModel_fwd.H"

#include <ablastr/fields/MultiFabRegister.H>

#include <AMReX_Array.H>
#include <AMReX_BoxArray.H>
#include <AMReX_DistributionMapping.H>
#include <AMReX_IntVect.H>
#include <AMReX_LO_BCTYPES.H>
#include <AMReX_REAL.H>

#include <optional>

/**
 * \brief Boundary handler for the global A recovery vector Poisson solve.
 *
 * Since the hybrid solver evolves only the plasma-generated part of the
 * fields (the external part is split off), the plasma-sourced vector
 * potential decays to zero at the domain walls. All non-periodic domain
 * boundaries are therefore homogeneous Dirichlet for every component of A,
 * matching the homogeneous Dirichlet condition applied on embedded
 * boundaries. The only exception is the r=0 axis in RZ which is Neumann.
 */
struct GlobalARecoveryBoundaryHandler
{
    amrex::Array<amrex::Array<amrex::LinOpBCType, AMREX_SPACEDIM>, 3> lobc, hibc;
    amrex::Array<amrex::Array<bool, AMREX_SPACEDIM*2>, 3> dirichlet_flag;
    bool has_non_periodic = false;
    bool bcs_set = false;

    /** Map the WarpX field boundary conditions to linear operator boundary
     *  conditions: periodic stays periodic, the RZ axis is Neumann and all
     *  other boundaries are homogeneous Dirichlet. */
    void define ();
};

/**
 * \brief This class recovers the vector potential A generated by the plasma
 * currents by solving the global vector Poisson equation
 * \f[
 *     \vec{\nabla}^2 \vec{A} = - \mu_0 \vec{J}
 * \f]
 * where the source current J = curl(B)/mu0 - J_ext is masked to zero in
 * vacuum cells (rho <= 0). The B field is then replaced by curl(A) in vacuum
 * cells (rho < n_floor*q_e) where the local Faraday update is unreliable,
 * while the integrated B field is kept inside the plasma. The E field in
 * vacuum cells is reconstructed from E = -dA/dt - grad(Pe)/rho using a BDF2
 * time derivative of the recovered A history.
 */
class GlobalARecovery
{
public:
    explicit GlobalARecovery (HybridPICModel const* hybrid_model);

    /** Read solver options from the hybrid_pic_model parameter group. */
    void ReadParameters ();

    /** Allocate the A, A history and scratch multifabs. */
    void AllocateLevelMFs (
        ablastr::fields::MultiFabRegister & fields,
        int lev, const amrex::BoxArray& ba, const amrex::DistributionMapping& dm,
        int ncomps,
        const amrex::IntVect& ngEB,
        const amrex::IntVect& ngRho,
        const amrex::IntVect& Ex_nodal_flag,
        const amrex::IntVect& Ey_nodal_flag,
        const amrex::IntVect& Ez_nodal_flag,
        const amrex::IntVect& Bx_nodal_flag,
        const amrex::IntVect& By_nodal_flag,
        const amrex::IntVect& Bz_nodal_flag
    ) const;

    /** Define boundary conditions and check geometry support. */
    void InitData ();

    /** Seed A^0 from the current (plasma-only) B field and charge density so
     *  that the first-step dA/dt is meaningful. Does not modify B. */
    void InitialSolve ();

    /** Rotate the A history (A_old <- A_prev <- A) at the start of a step. */
    void AdvanceHistory ();

    /**
     * \brief Recover A from the plasma current implied by the given B field
     * and replace B with curl(A) in vacuum cells.
     *
     * \param[in,out] Bfield     plasma-only B field to correct in vacuum
     * \param[in] rho_blend      nodal charge density used for the source mask
     *                           and the plasma/vacuum blend
     * \param[in] ng             number of guard cells to fill on B
     * \param[in] nodal_sync     whether to synchronize nodal points
     */
    void RecoverB (
        ablastr::fields::MultiLevelVectorField const& Bfield,
        ablastr::fields::MultiLevelScalarField const& rho_blend,
        amrex::IntVect ng, std::optional<bool> nodal_sync);

    /**
     * \brief Overwrite E with -dA/dt - grad(Pe)/rho in vacuum cells
     * (rho < n_floor*q_e), using BDF2 for dA/dt once enough history exists.
     *
     * \param[in,out] Efield     plasma-only E field to correct in vacuum
     * \param[in] rhofield       nodal charge density at the new time
     * \param[in] dt             full timestep size
     * \param[in] ng             number of guard cells to fill on E
     * \param[in] nodal_sync     whether to synchronize nodal points
     */
    void ReconstructVacuumE (
        ablastr::fields::MultiLevelVectorField const& Efield,
        ablastr::fields::MultiLevelScalarField const& rhofield,
        amrex::Real dt,
        amrex::IntVect ng, std::optional<bool> nodal_sync);

    /** Relative tolerance of the vector Poisson solve */
    amrex::Real m_rtol = 1.0e-8;
    /** Absolute tolerance of the vector Poisson solve */
    amrex::Real m_atol = 0.0;
    /** Maximum number of MLMG iterations */
    int m_max_iters = 100;
    /** MLMG verbosity */
    int m_verbosity = 0;

    // The member functions below contain extended __device__ lambdas.
    // In order to compile with nvcc, they need to be public.

    /** Fill hybrid_J_fp_nodal with the plasma current interpolated to the
     *  nodal grid, masked to zero where the charge density vanishes. */
    void BuildMaskedNodalSource (
        ablastr::fields::MultiLevelScalarField const& rho_mask);

    /** Zero the Dirichlet domain boundary nodes of the nodal A guess. */
    void ZeroDirichletBoundaryNodes ();

    /** Interpolate the nodal A solution onto the edge (E) staggering.
     *
     *  With the conformal embedded-boundary solve, cut edges receive the
     *  average of A over their uncovered segment instead of the edge-center
     *  value: the recovered A vanishes on the embedded surface (homogeneous
     *  Dirichlet), so along a cut edge A closes linearly to zero at the cut
     *  point and the segment average is half the fluid-endpoint value. This
     *  is the value the conformal (length-weighted) circulations expect, and
     *  it makes the reconstructed vacuum E = -dA/dt consistent on cut edges.
     */
    void InterpNodalAToEdge ();

    /** Compute B_from_A = curl(A) on the B staggering: the nodal solution is
     *  interpolated to the edges, the standard curl is taken, and with the
     *  conformal embedded-boundary solve the cut faces are recomputed from
     *  the conformal circulation (see ConformalizeBFromA). */
    void ComputeBFromA ();

    /** Recompute B_from_A on cut faces from the conformal circulation of the
     *  nodal A around the uncovered face contour:
     *
     *      B * S_cut = sum_edges (+/-) integral_(uncovered segment) A . dl
     *
     *  using the enlarged-cell-technique geometry (face areas and edge
     *  lengths). The segment integrals are trapezoids of the nodal A; on cut
     *  edges A closes linearly to zero at the cut point (the recovery solves
     *  with homogeneous Dirichlet A on the embedded surface, so the closing
     *  segment along the surface contributes nothing). This is exact for
     *  linear A and second-order accurate in general, and it places blended
     *  faces in the same discrete flux space as the conformally evolved
     *  ones, removing the stair-step mismatch of the standard curl at the
     *  walls. Faces with zero uncovered area are left to the mirror fill. */
    void ConformalizeBFromA ();

    /** Replace B with curl(A) where the charge density interpolated to the
     *  B staggering is below n_floor*q_e. */
    void BlendB (
        ablastr::fields::MultiLevelVectorField const& Bfield,
        ablastr::fields::MultiLevelScalarField const& rho_blend);

private:
    /** Solve the vector Poisson equation for the nodal A using the previous
     *  solution as initial guess. */
    void SolveA ();

    HybridPICModel const* m_hybrid_model;

    GlobalARecoveryBoundaryHandler m_boundary_handler;

    /** Number of valid A time levels accumulated (saturates at 3). BDF2 is
     *  used for dA/dt once 3 levels (A, A_prev, A_old) are distinct. */
    int m_history_count = 0;
};

#endif // WARPX_GLOBAL_A_RECOVERY_H_
